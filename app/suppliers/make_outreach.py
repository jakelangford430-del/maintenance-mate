#!/usr/bin/env python3
"""Build join-form tokens, the server-side join index, per-channel recipient CSVs and outreach drafts.
Sends NOTHING. Respects the opt-out list (app/data/optouts.csv plus --optouts export from /api/optouts).
Usage: python3 suppliers/make_outreach.py [--base https://your-site.netlify.app] [--optouts optouts.json]"""
import json,csv,secrets,argparse,re,pathlib,datetime
ap=argparse.ArgumentParser();ap.add_argument('--base',default='https://your-site.netlify.app');ap.add_argument('--optouts');a=ap.parse_args()
A=pathlib.Path(__file__).resolve().parent.parent;D=A/'data';O=A/'outreach';O.mkdir(exist_ok=True)
C=json.load(open(D/'contacts.json'))['suppliers']
TK=D/'join_tokens.json';tok=json.load(open(TK)) if TK.exists() else {}
# opt-outs: local file + optional export of the live table
opt={}
of=D/'optouts.csv'
if not of.exists():of.write_text('supplier,channel,reason,recorded_by,date\n')
for r in csv.DictReader(open(of)):opt.setdefault(r['supplier'],set()).add(r['channel'] or 'all')
if a.optouts:
  for r in json.load(open(a.optouts)).get('optouts',[]):opt.setdefault(r['supplier'],set()).add(r['channel'])
blocked=lambda n,ch:bool(opt.get(n,set())&{'all',ch})
v=lambda x,k:'' if (x['f'].get(k) or {}).get('verify') else (x['f'].get(k) or {}).get('v','')
idx={}
for x in C:
  n=x['name']
  if n not in tok:tok[n]=secrets.token_urlsafe(9)
  if blocked(n,'all'):continue
  def suburb(a):
    import re
    if not a:return ''
    p=[q.strip() for q in a.split(',') if q.strip()]
    t=p[-1] if p else ''
    t=re.sub(r'\b(WA|Western Australia|Australia|\d{4})\b','',t).strip(' ,')
    t=re.sub(r'^\d+[\w/-]*\s+.*\b(St|Street|Rd|Road|Ave|Avenue|Dr|Drive|Way|Pl|Cres|Hwy|Ct|Pde|Blvd|Lane|Ln)\b\s*','',t,flags=re.I).strip()
    return t if t and not re.match(r'^\d',t) else ''
  idx[tok[n]]={'n':n,'p':{k:val for k,val in {'business':n,'email':v(x,'email'),'mobile':v(x,'mobile'),'website':v(x,'form') or v(x,'website'),'areas':suburb(v(x,'area') or v(x,'address')),'offices':x.get('offices',[])}.items() if val}}
json.dump(tok,open(TK,'w'),indent=0)
(A.parent/'netlify-site/netlify/lib/join_index.js').write_text('// Generated by app/suppliers/make_outreach.py. Token -> supplier + prefill. Server-side only.\nexport const JOIN = '+json.dumps(idx,separators=(',',':'))+';\n')
# who to invite: anyone missing email, mobile or the join-only details (ABN, insurance) = everyone not yet joined
done={n for n in tok if False}
rows={'email':[],'sms':[],'form':[]};none=[]
for x in C:
  n=x['name']
  if blocked(n,'all'):continue
  miss=[k for k in ('email','mobile','abn','insurance') if not v(x,k)]
  if not miss:continue
  link=f"{a.base}/join?s={tok[n]}"
  base={'supplier':n,'offices':'; '.join(x.get('offices',[])),'trades':'; '.join(x.get('trades',[])),'used_jobs':x.get('used',0),'missing':'; '.join(miss),'join_link':link}
  ch=None
  if v(x,'email') and not blocked(n,'email'):ch='email';base['to']=v(x,'email')
  elif v(x,'mobile') and not blocked(n,'sms'):ch='sms';base['to']=v(x,'mobile')
  elif v(x,'form') and not blocked(n,'form'):ch='form';base['to']=v(x,'form')
  if ch:base['source']=(x['f'][{'sms':'mobile'}.get(ch,ch)]).get('src','');rows[ch].append(base)
  else:none.append({**base,'to':v(x,'phone'),'source':'no email, mobile or form found'})
for ch,L in [*rows.items(),('phone_only_or_none',none)]:
  L.sort(key=lambda r:(-r['used_jobs'],r['supplier']))
  with open(O/f'recipients_{ch}.csv','w',newline='') as f:
    w=csv.DictWriter(f,['supplier','to','offices','trades','used_jobs','missing','join_link','source']);w.writeheader();w.writerows(L)
# drafts
L0=f"{a.base}/join?s="+'X'*12
sms=f"Example Property Co: join our supplier list for rental repair jobs: {L0} Reply STOP to opt out"
email=f"""Subject: Quote requests from Example Property Co

Hi {{contact_name_or_business}},

We manage rental properties across Mandurah, Perth, Bunbury and Geraldton and we'd like to send you quote requests for {{trade}} work in your area.

If you're interested, please check and complete your details here (takes about 2 minutes):
{{join_link}}

We've filled in what we could find publicly. You can also tell us how you'd prefer to get quote requests (email, text, phone or your website form).

If you'd rather not hear from us, just reply "no thanks" or use the "Don't contact me again" button on the form.

Thanks,
{{pm_name}}
Example Property Co, {{office}}"""
formv=f"""Hi, this is {{pm_name}} from Example Property Co. We manage rental properties in {{office}} and would like to send you quote requests for {{trade}} work. Could you add your details to our preferred supplier list here: {{join_link}} (about 2 minutes). Or reply with the best email or mobile for quote requests. If you'd rather not be contacted, let us know and we won't message again. Thanks!"""
(O/'outreach_drafts.md').write_text(f"""# Supplier outreach drafts (NOT SENT; nothing is sent by the portal)
Generated {datetime.date.today():%d %b %Y}. Each recipient's personal link is in the recipients_*.csv files. Opt-outs are excluded.

## SMS ({len(sms)} characters with a real-length link, limit 160)
{sms}

## Email
{email}

## Facebook message / website contact form
{formv}
""")
cnt={k:len(L) for k,L in rows.items()};cnt['phone_only_or_none']=len(none);cnt['opted_out']=sum(1 for n in opt if blocked(n,'all'));cnt['sms_chars']=len(sms)
print(json.dumps(cnt))
