// Regenerates netlify/lib/tenant_categories.js from the editable list in design/maintenance-mate/tenant-form-categories.json
// Usage: node gen_tenant_categories.cjs
const fs = require("fs"), path = require("path");
const src = path.join(__dirname, "..", "design", "maintenance-mate", "tenant-form-categories.json");
const out = path.join(__dirname, "netlify", "lib", "tenant_categories.js");
const j = JSON.parse(fs.readFileSync(src, "utf8"));
const body = "// GENERATED by gen_tenant_categories.cjs from design/maintenance-mate/tenant-form-categories.json. Edit the JSON, then regenerate.\n" +
  "export const CATEGORIES = " + JSON.stringify(j.categories) + ";\n" +
  "export const EMERGENCY = " + JSON.stringify(j.emergency) + ";\n";
fs.writeFileSync(out, body);
console.log("wrote", path.relative(process.cwd(), out), j.categories.length, "categories");
